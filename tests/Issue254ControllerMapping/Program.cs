using ShinGetterMod.Services;

int checks = 0;
void Check(bool value, string message) { checks++; if (!value) throw new Exception(message); }
var defaults = new Dictionary<string, string> { ["ui_up"] = "north", ["ui_down"] = "south", ["ui_select"] = "face_south", ["ui_cancel"] = "face_east" };
var declared = new HashSet<string>(defaults.Keys.Concat(defaults.Values));
var original = new Dictionary<string, string> { ["ui_up"] = "beta_up", ["ui_down"] = "beta_down", ["ui_select"] = "face_east", ["ui_cancel"] = "face_south" };
var repaired = ShinGetterControllerMappingPolicy.Normalize(original, defaults, declared.Contains, out int count);
Check(count == 2 && repaired["ui_up"] == "north" && repaired["ui_down"] == "south", "invalid Beta values not restored to current defaults");
Check(repaired["ui_select"] == "face_east" && repaired["ui_cancel"] == "face_south", "valid custom swaps lost");
Check(original["ui_up"] == "beta_up" && original["ui_select"] == "face_east", "original saved/runtime source mutated");
Check(!ReferenceEquals(repaired, original), "repair changed source in place");
var again = ShinGetterControllerMappingPolicy.Normalize(repaired, defaults, declared.Contains, out count);
Check(count == 0 && ReferenceEquals(again, repaired), "valid warm map unnecessarily copied");
var betaDeclared = new HashSet<string>(declared) { "beta_up", "beta_down" };
var beta = ShinGetterControllerMappingPolicy.Normalize(original, defaults, betaDeclared.Contains, out count);
Check(count == 0 && ReferenceEquals(beta, original), "current valid Beta actions were rewritten");
var unknown = new Dictionary<string, string>(original) { ["missing_key"] = "face_east", ["valid_extra"] = "missing_value" };
declared.Add("valid_extra");
var filtered = ShinGetterControllerMappingPolicy.Normalize(unknown, defaults, declared.Contains, out count);
Check(!filtered.ContainsKey("missing_key") && !filtered.ContainsKey("valid_extra"), "no valid fallback kept invalid mapping");
Check(unknown.ContainsKey("missing_key") && unknown.ContainsKey("valid_extra"), "unknown source fields deleted");
var invalidDefault = new Dictionary<string, string>(defaults) { ["ui_up"] = "also_invalid" };
var dropped = ShinGetterControllerMappingPolicy.Normalize(original, invalidDefault, declared.Contains, out count);
Check(!dropped.ContainsKey("ui_up") && dropped["ui_down"] == "south", "invalid default was consumed");
var manager = new MegaCrit.Sts2.Core.Nodes.CommonUi.NInputManager();
Godot.InputMap.Actions.UnionWith(new[] { "ui_up", "ui_select", "north", "face_east" });
manager.ControllerManager.GetDefaultControllerInputMap = new() { ["ui_up"] = "north", ["ui_select"] = "face_east" };
var saved = new Dictionary<Godot.StringName, Godot.StringName> { ["ui_up"] = "beta_up", ["ui_select"] = "face_east" };
manager.Install(new(saved));
ShinGetterMod.Patches.ShinGetterControllerMappingCompatibility.EnsureValid(manager);
Check(manager.Runtime["ui_up"].Value == "north" && saved["ui_up"].Value == "beta_up", "runtime repair changed saved map");
int callsAfterCold = Godot.InputMap.Calls;
ShinGetterMod.Patches.ShinGetterControllerMappingCompatibility.EnsureValid(manager);
Check(Godot.InputMap.Calls == callsAfterCold, "warm input rescanned mapping");
var prefix = HarmonyLib.AccessTools.Method(typeof(ShinGetterMod.Patches.ShinGetterControllerMappingRebindPatch), "Prefix");
prefix.Invoke(null, new object[] { manager });
manager.ModifyControllerButton("ui_up", "beta_up");
ShinGetterMod.Patches.ShinGetterControllerMappingCompatibility.EnsureValid(manager);
Check(manager.Runtime["ui_up"].Value == "north" && Godot.InputMap.Calls > callsAfterCold, "in-place setter bypassed invalidation");
manager.Install(new(saved));
ShinGetterMod.Patches.ShinGetterControllerMappingCompatibility.EnsureValid(manager);
Check(manager.Runtime["ui_up"].Value == "north", "replacement controller dictionary bypassed validation");
Check(saved["ui_up"].Value == "beta_up" && saved["ui_select"].Value == "face_east", "source saved bindings were modified");
Console.WriteLine($"PASS: {checks} linked production controller-policy/Harmony FieldRef assertions (not physical input proof)");
